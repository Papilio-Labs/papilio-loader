import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import {
  buildBoardProvisioningRegions,
  buildNvsPartition,
  buildOtadataSelectingSlot,
  crc32,
  parsePartitionTable,
  provisionMergedImage,
  seedBootSelectionInMergedImage,
  validatePapilioLoaderFactoryImage,
  validateMergedLoaderImage,
  validateSupportedLoaderPartitionTable,
} from "../src/nvs-image.js";

const fixture = (name: string) => new Uint8Array(readFileSync(new URL(`./fixtures/${name}`, import.meta.url)));

function partitionEntry(label: string, type: number, subtype: number, offset: number, size: number): Uint8Array {
  const entry = new Uint8Array(32);
  const dv = new DataView(entry.buffer);
  entry.set([0xaa, 0x50, type, subtype]);
  dv.setUint32(4, offset, true);
  dv.setUint32(8, size, true);
  entry.set(new TextEncoder().encode(label), 12);
  return entry;
}

function supportedPartitionTable(): Uint8Array {
  const table = new Uint8Array(0xc00).fill(0xff);
  const entries = [
    partitionEntry("nvs_loader", 1, 0x02, 0x9000, 0x3000),
    partitionEntry("otadata", 1, 0x00, 0xc000, 0x2000),
    partitionEntry("nvs", 1, 0x02, 0xe000, 0x6000),
    partitionEntry("factory", 0, 0x00, 0x20000, 0xe0000),
    partitionEntry("ota_0", 0, 0x10, 0x100000, 0x180000),
    partitionEntry("ota_1", 0, 0x11, 0x280000, 0x180000),
  ];
  entries.forEach((entry, index) => table.set(entry, index * 32));
  const checksumOffset = entries.length * 32;
  table[checksumOffset] = 0xeb;
  table[checksumOffset + 1] = 0xeb;
  table.set(createHash("md5").update(table.subarray(0, checksumOffset)).digest(), checksumOffset + 16);
  return table;
}

function factoryImage(version: string): Uint8Array {
  const image = new Uint8Array(0x100).fill(0xff);
  image[0] = 0xe9;
  image.set([0x32, 0x54, 0xcd, 0xab], 0x20);
  image.fill(0, 0x30, 0x50);
  image.fill(0, 0x50, 0x70);
  image.set(new TextEncoder().encode(version), 0x30);
  image.set(new TextEncoder().encode("papilio_esp_bootloader"), 0x50);
  return image;
}

describe("nvs-image", () => {
  it("crc32 matches zlib semantics", () => {
    expect(crc32(new TextEncoder().encode("123456789"))).toBe(0xcbf43926);
  });

  // Reference generated by esp-idf-nvs-partition-gen from nvs_loader_ref.csv.
  it("builds NVS images byte-identical to nvs_partition_gen", () => {
    const image = buildNvsPartition(
      {
        wifi_cfg: {
          ssid: { type: "string", value: "MyNetwork-With-A-Long-Name-32ch" },
          pass: { type: "string", value: "s3cret pass!" },
        },
        loader: { last_slot: { type: "u8", value: 0 } },
      },
      0x3000
    );
    expect(Buffer.from(image).equals(Buffer.from(fixture("nvs_loader_ref.bin")))).toBe(true);
  });

  it("builds otadata selecting ota_0 like otatool", () => {
    expect(Buffer.from(buildOtadataSelectingSlot(0)).equals(Buffer.from(fixture("otadata_ota0_ref.bin")))).toBe(true);
  });

  it("parses the partition table and builds provisioning regions", () => {
    const table = new Uint8Array(0xc00).fill(0xff);
    table.set(partitionEntry("nvs_loader", 1, 0x02, 0x9000, 0x3000), 0);
    table.set(partitionEntry("otadata", 1, 0x00, 0xc000, 0x2000), 32);
    table.set(partitionEntry("nvs", 1, 0x02, 0xe000, 0x6000), 64);
    table.set(partitionEntry("factory", 0, 0x00, 0x20000, 0xe0000), 96);
    table.set(partitionEntry("ota_0", 0, 0x10, 0x100000, 0x180000), 128);
    const partitions = parsePartitionTable(table);
    expect(partitions.map((p) => p.label)).toEqual(["nvs_loader", "otadata", "nvs", "factory", "ota_0"]);

    const regions = buildBoardProvisioningRegions(partitions, { ssid: "net", password: "pw" });
    expect(regions.map((r) => [r.address, r.data.length])).toEqual([
      [0x9000, 0x3000],
      [0xc000, 0x2000],
      [0xe000, 0x6000],
    ]);
  });

  it("validates the supported loader layout and partition-table MD5 record", () => {
    const table = supportedPartitionTable();
    const partitions = validateSupportedLoaderPartitionTable(
      table,
      (data) => createHash("md5").update(data).digest()
    );
    expect(partitions.map((partition) => partition.label)).toEqual([
      "nvs_loader", "otadata", "nvs", "factory", "ota_0", "ota_1",
    ]);

    table[0] ^= 1;
    expect(() => validateSupportedLoaderPartitionTable(
      table,
      (data) => createHash("md5").update(data).digest()
    )).toThrow(/MD5 checksum/);
  });

  it("requires the supported Papilio loader factory identity and minimum version", () => {
    expect(validatePapilioLoaderFactoryImage(factoryImage("0.1.2"))).toBe("0.1.2");
    expect(() => validatePapilioLoaderFactoryImage(factoryImage("0.1.1"))).toThrow(/older than supported/);
    const wrongProject = factoryImage("0.1.2");
    wrongProject.set(new TextEncoder().encode("other_project"), 0x50);
    expect(() => validatePapilioLoaderFactoryImage(wrongProject)).toThrow(/Unsupported factory application/);
  });

  it("pads only the verified published short migration image and preserves full images", () => {
    const md5 = (data: Uint8Array) => createHash("md5").update(data).digest();
    const publishedDigest = Buffer.from("757f350753975d7ff097888bd7e2776862ac765c29959253b56b7de97b32f128", "hex");
    const short = new Uint8Array(2543808).fill(0xff);
    short[0] = 0xe9;
    short.set(supportedPartitionTable(), 0x8000);
    short.set(factoryImage("0.1.3"), 0x20000);
    const padded = validateMergedLoaderImage(short, md5, () => publishedDigest);
    expect(padded.length).toBe(0x400000);
    expect(Buffer.from(padded.subarray(0, short.length)).equals(Buffer.from(short))).toBe(true);
    expect(padded.subarray(short.length).every((byte) => byte === 0xff)).toBe(true);
    expect(validateMergedLoaderImage(padded, md5, () => { throw new Error("unexpected hash"); })).toBe(padded);
    expect(() => validateMergedLoaderImage(short, md5, (data) => createHash("sha256").update(data).digest()))
      .toThrow(/verified v2.2.3/);
    expect(() => validateMergedLoaderImage(short.subarray(0, short.length - 1), md5, () => publishedDigest))
      .toThrow(/verified v2.2.3/);
  });

  it("rejects keys longer than 15 bytes", () => {
    expect(() => buildNvsPartition({ ns: { "sixteen_chars_xx": { type: "u8", value: 1 } } }, 0x3000)).toThrow();
  });

  it("seeds otadata and last_slot into a blank merged image", () => {
    const image = new Uint8Array(0x100010).fill(0xff);
    image.set(partitionEntry("nvs_loader", 1, 0x02, 0x9000, 0x3000), 0x8000);
    image.set(partitionEntry("otadata", 1, 0x00, 0xc000, 0x2000), 0x8020);
    image.set(partitionEntry("ota_0", 0, 0x10, 0x100000, 0x180000), 0x8040);
    image[0x100000] = 0xe9;

    const seeded = seedBootSelectionInMergedImage(image);
    expect(seeded).not.toBeNull();
    expect(Buffer.from(seeded!.subarray(0xc000, 0xe000)).equals(Buffer.from(fixture("otadata_ota0_ref.bin")))).toBe(true);
    expect(Buffer.from(seeded!.subarray(0x9000, 0xc000)).equals(
      Buffer.from(buildNvsPartition({ loader: { last_slot: { type: "u8", value: 0 } } }, 0x3000))
    )).toBe(true);
    expect(image[0xc000]).toBe(0xff);

    // Already seeded, or no app in ota_0 → left alone.
    expect(seedBootSelectionInMergedImage(seeded!)).toBeNull();
    image[0x100000] = 0xff;
    expect(seedBootSelectionInMergedImage(image)).toBeNull();
  });

  it("writes WiFi settings and boot selection into a merged image in one go", () => {
    const image = new Uint8Array(0x100010).fill(0xff);
    image.set(partitionEntry("nvs_loader", 1, 0x02, 0x9000, 0x3000), 0x8000);
    image.set(partitionEntry("otadata", 1, 0x00, 0xc000, 0x2000), 0x8020);
    image.set(partitionEntry("nvs", 1, 0x02, 0xe000, 0x6000), 0x8040);
    image.set(partitionEntry("ota_0", 0, 0x10, 0x100000, 0x180000), 0x8060);
    image[0x100000] = 0xe9;

    const out = provisionMergedImage(image, { ssid: "net", password: "pw" });
    const regions = buildBoardProvisioningRegions(parsePartitionTable(image.subarray(0x8000, 0x8000 + 0xc00)), {
      ssid: "net",
      password: "pw",
    });
    expect(regions.length).toBe(3);
    for (const r of regions) {
      expect(Buffer.from(out.subarray(r.address, r.address + r.data.length)).equals(Buffer.from(r.data))).toBe(true);
    }
    // The app and the rest of the image are untouched, and the input is not modified.
    expect(out[0x100000]).toBe(0xe9);
    expect(image[0xe000]).toBe(0xff);
  });

  it("refuses images that are not merged images or do not cover the settings area", () => {
    expect(() => provisionMergedImage(new Uint8Array(0x1000), { ssid: "a", password: "b" })).toThrow(/merged image/);
    const short = new Uint8Array(0x8000 + 0xc00).fill(0xff);
    short.set(partitionEntry("otadata", 1, 0x00, 0xc000, 0x2000), 0x8000);
    short.set(partitionEntry("nvs", 1, 0x02, 0xe000, 0x6000), 0x8020);
    short.set(partitionEntry("ota_0", 0, 0x10, 0x100000, 0x180000), 0x8040);
    expect(() => provisionMergedImage(short, { ssid: "a", password: "b" })).toThrow(/does not cover/);
  });
});
